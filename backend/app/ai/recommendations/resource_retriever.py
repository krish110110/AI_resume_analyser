    async def get_resources(self, skill: str) -> list[dict]:
        canonical = normalize_skill(skill) or skill
        url = self.OFFICIAL_DOCS.get(canonical)
        if not url:
            return []
        return [{"title": f"{canonical} official documentation", "url": url, "skill": canonical}]